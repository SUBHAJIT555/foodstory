export function mediaFor(...keys: Array<string | undefined>): string | undefined {
  for (const key of keys) {
    if (!key) continue;
    const slug = slugFrom(key);
    if (bySlug[slug]) return bySlug[slug];
    const named = byName[norm(key)];
    if (named) return named;
  }
  return undefined;
}

export function galleryFor(slug: string, name: string): string[] {
  if (galleries[slug]) return galleries[slug];
  const primary = mediaFor(slug, name);
  return primary ? [primary] : [];
}
